'use strict';
const { contextBridge, ipcRenderer } = require('electron');

const call = async (channel, arg) => {
  const r = await ipcRenderer.invoke(channel, arg);
  if (!r.ok) throw new Error(r.error);
  return r.data;
};

contextBridge.exposeInMainWorld('stalow', {
  search: (q) => call('catalog:search', q),
  artists: (text) => call('catalog:artists', text),
  channels: (category, text) => call('catalog:channels', { category, text }),
  home: (recentArtistIds) => call('catalog:home', recentArtistIds),
  artist: (id) => call('catalog:artist', id),
  shelf: (id, name, more) => call('catalog:shelf', { id, name, more }),
  album: (id) => call('catalog:album', id),
  playlist: (id) => call('catalog:playlist', id),
  radio: (videoId, continuation) => call('catalog:radio', { videoId, continuation }),
  play: (id) => call('player:play', id),
  resume: () => call('player:resume'),
  pause: () => call('player:pause'),
  seek: (s) => call('player:seek', s),
  volume: (v) => call('player:volume', v),
  settings: () => call('app:settings'),
  signIn: () => call('app:signin'),
  togglePlayer: () => call('app:togglePlayer'),
  openExternal: (url) => call('app:openExternal', url),
  checkUpdates: () => call('app:checkUpdates'),
  installUpdate: (resume) => call('app:installUpdate', resume),
  saveSession: (session) => call('app:saveSession', session),
  setSetting: (key, value) => call('settings:set', { key, value }),
  getData: (name) => call('data:get', name),
  setData: (name, value) => call('data:set', { name, value }),
  lyrics: (want) => call('lyrics:get', want),
  cacheSize: () => call('storage:cacheSize'),
  clearCache: () => call('storage:clearCache'),
  exportBackup: (extra) => call('backup:export', extra),
  importBackup: () => call('backup:import'),
  download: (songs) => call('download:add', songs),
  cancelDownload: (id) => call('download:cancel', id),
  retryDownloads: () => call('download:retry'),
  downloadJobs: () => call('download:jobs'),
  onDownloadJobs: (fn) => ipcRenderer.on('download-jobs', (_e, jobs) => fn(jobs)),
  downloads: () => call('download:list'),
  removeDownload: (id) => call('download:remove', id),
  openDownloadsFolder: () => call('download:openFolder'),
  setPlaying: (playing) => call('app:playing', playing),
  onDownload: (fn) => ipcRenderer.on('download', (_e, ev) => fn(ev)),
  syncInfo: () => call('sync:info'),
  syncCreate: () => call('sync:create'),
  syncJoin: (code) => call('sync:join', code),
  syncLeave: (erase) => call('sync:leave', erase),
  syncNow: () => call('sync:now'),
  onSync: (fn) => ipcRenderer.on('sync', (_e, info) => fn(info)),
  onSynced: (fn) => ipcRenderer.on('synced', (_e, what) => fn(what)),
  loadSession: () => call('app:loadSession'),
  onPlayer: (fn) => ipcRenderer.on('player', (_e, ev) => fn(ev)),
  onUpdate: (fn) => ipcRenderer.on('update', (_e, ev) => fn(ev)),
});
